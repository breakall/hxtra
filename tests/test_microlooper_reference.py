ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tests/microlooper_reference.cpp'


def compile_oracle(out):
    compiler = shutil.which('clang++') or shutil.which('g++')
    if compiler is None:
        pytest.skip('micro-looper reference tests need clang++ or g++')
    args = [compiler, '-std=c++17', '-O1', '-g', '-Wall', '-Wextra', '-Werror',
            '-fsanitize=address,undefined', '-fno-omit-frame-pointer', '-ffp-contract=off',
            '-I', str(ROOT / 'tools'), str(SOURCE), '-o', str(out)]
    r = subprocess.run(args, capture_output=True, text=True, timeout=90)
    assert r.returncode == 0, r.stdout + r.stderr
    return out


@pytest.fixture(scope='module')
def oracle(tmp_path_factory):
    return compile_oracle(tmp_path_factory.mktemp('microlooper') / 'reference')


@pytest.mark.parametrize('case', ['transport', 'clock', 'overdub', 'splices', 'shorten-envelope'])
def test_reference_behavior(oracle, case):
    r = subprocess.run([str(oracle), case], capture_output=True, text=True, timeout=90)
    assert r.returncode == 0, r.stdout + r.stderr



